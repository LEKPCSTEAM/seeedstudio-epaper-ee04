#!/usr/bin/env python3
"""Generate Prompt GFX fonts and pre-shaped Thai run bitmaps. Run with system python3 (Pillow+raqm)."""
import argparse
import re
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "assets" / "fonts"
OUT_FONTS = ROOT / "src" / "ui" / "fonts"
OUT_RUNS = ROOT / "src" / "ui" / "text" / "ThaiRunsData.cpp"
GFXFF = ROOT / ".pio/libdeps/ee04_debug/Seeed_GFX2/src/font/GFXFF"

# (Fonts::Id name, weight, English counterpart header)
IDS = [
    ("kSans9", "Regular", "FreeSans9pt7b"),
    ("kSans12", "Regular", "FreeSans12pt7b"),
    ("kSans18", "Regular", "FreeSans18pt7b"),
    ("kBold9", "SemiBold", "FreeSansBold9pt7b"),
    ("kBold12", "SemiBold", "FreeSansBold12pt7b"),
    ("kBold18", "SemiBold", "FreeSansBold18pt7b"),
    ("kBold24", "SemiBold", "FreeSansBold24pt7b"),
]
HEADER_LINE = "// Generated by scripts/gen_thai_assets.py; do not edit.\n"
PAD = 24


def english_h_height(name):
    text = (GFXFF / f"{name}.h").read_text()
    glyphs = re.search(r"GFXglyph \w+Glyphs\[\][^{]*\{(.*?)\};", text, re.S).group(1)
    ents = re.findall(r"\{\s*(\d+),\s*(\d+),\s*(\d+),\s*(\d+),\s*(-?\d+),\s*(-?\d+)\s*\}", glyphs)
    return int(ents[ord("H") - 0x20][2])


def load(weight, px, raqm):
    engine = ImageFont.Layout.RAQM if raqm else ImageFont.Layout.BASIC
    return ImageFont.truetype(str(FONT_DIR / f"Prompt-{weight}.ttf"), px, layout_engine=engine)


def render(font, text, language=None):
    """Return (bitmap L-image cropped to ink or None, left, top) relative to origin/baseline."""
    w = int(font.getlength(text)) + PAD * 2 + font.size
    h = font.size * 3
    img = Image.new("1", (w, h), 0)
    d = ImageDraw.Draw(img)
    d.fontmode = "1"
    kw = {"language": language} if language else {}
    d.text((PAD, font.size * 2), text, font=font, fill=1, anchor="ls", **kw)
    box = img.getbbox()
    if box is None:
        return None, 0, 0
    return img.crop(box), box[0] - PAD, box[1] - font.size * 2


def pick_px(weight, target):
    best = None
    for px in range(4, 120):
        bm, _, _ = render(load(weight, px, False), "H")
        if bm is None:
            continue
        diff = abs(bm.height - target)
        if best is None or diff < best[0]:
            best = (diff, px)
    if best is None:
        sys.exit(f"no pixel size for {weight}")
    return best[1]


def pack_gfx(bm):
    bits = []
    for y in range(bm.height):
        for x in range(bm.width):
            bits.append(1 if bm.getpixel((x, y)) else 0)
    while len(bits) % 8:
        bits.append(0)
    return [int("".join(map(str, bits[i:i + 8])), 2) for i in range(0, len(bits), 8)]


def pack_rows(bm):
    out = []
    for y in range(bm.height):
        for bx in range(0, bm.width, 8):
            v = 0
            for k in range(8):
                v <<= 1
                if bx + k < bm.width and bm.getpixel((bx + k, y)):
                    v |= 1
            out.append(v)
    return out


def hex_rows(data, per=12):
    return ",\n".join("  " + ", ".join(f"0x{b:02X}" for b in data[i:i + per]) for i in range(0, len(data), per))


def gen_ascii(weight, px):
    font = load(weight, px, False)
    asc, desc = font.getmetrics()
    blob, glyphs = [], []
    for code in range(0x20, 0x7F):
        bm, left, top = render(font, chr(code))
        adv = round(font.getlength(chr(code)))
        offset = len(blob)
        if bm is None:
            glyphs.append((offset, 0, 0, adv, 0, 0))
            continue
        blob += pack_gfx(bm)
        glyphs.append((offset, bm.width, bm.height, adv, left, top))
    name = f"Prompt_{weight}_{px}"
    lines = [HEADER_LINE, "#pragma once\n", "#include <Seeed_GFX.h>\n\n"]
    lines.append(f"const uint8_t {name}Bitmaps[] PROGMEM = {{\n{hex_rows(blob)}}};\n\n")
    lines.append(f"const GFXglyph {name}Glyphs[] PROGMEM = {{\n")
    for i, g in enumerate(glyphs):
        lines.append(f"  {{{g[0]}, {g[1]}, {g[2]}, {g[3]}, {g[4]}, {g[5]}}}"
                     f"{',' if i < len(glyphs) - 1 else ''} // 0x{0x20 + i:02X}\n")
    lines.append("};\n\n")
    lines.append(f"const GFXfont {name} PROGMEM = {{\n  (uint8_t *){name}Bitmaps,\n"
                 f"  (GFXglyph *){name}Glyphs,\n  0x20, 0x7E, {asc + desc}}};\n")
    (OUT_FONTS / f"{name}.h").write_text("".join(lines))
    return name, len(blob)


def is_thai(c):
    return 0x0E00 <= ord(c) <= 0x0E7F


def split_runs(s):
    runs, cur = [], ""
    for c in s:
        if cur and (is_thai(c) or c in "./"):
            cur += c
        elif is_thai(c):
            cur = c
        else:
            if cur:
                runs.append(cur)
            cur = ""
    if cur:
        runs.append(cur)
    return runs


TOKEN = re.compile(r'"(?:[^"\\\n]|\\.)*"|\'(?:[^\'\\\n]|\\.)*\'|//[^\n]*|/\*.*?\*/', re.S)


def scan_runs():
    runs = set()
    skip = [OUT_RUNS, OUT_FONTS]
    for path in sorted((ROOT / "src").rglob("*")):
        if path.suffix not in (".h", ".cpp") or any(path == s or s in path.parents for s in skip):
            continue
        for tok in TOKEN.findall(path.read_text(encoding="utf-8")):
            if tok.startswith('"'):
                runs.update(split_runs(tok[1:-1]))
    return sorted(runs)


def gen_runs(runs, sizes):
    items, total = [], 0
    for text in runs:
        for fid, (_, weight, _) in enumerate(IDS):
            font = load(weight, sizes[fid], True)
            bm, left, top = render(font, text, "th")
            if bm is None:
                continue
            data = pack_rows(bm)
            total += len(data)
            items.append((text, fid, bm.width, bm.height, left, top, round(font.getlength(text, language="th")), data))
    out = [HEADER_LINE, '#include "ui/text/ThaiRuns.h"\n\nnamespace {\n\n']
    for i, it in enumerate(items):
        out.append(f"const uint8_t kBits{i}[] PROGMEM = {{\n{hex_rows(it[7], 16)}}};\n")
    out.append("\n} // namespace\n\nextern const ThaiRun kThaiRuns[] = {\n")
    for i, it in enumerate(items):
        out.append(f'  {{"{it[0]}", {it[1]}, {it[2]}, {it[3]}, {it[4]}, {it[5]}, {it[6]}, kBits{i}}},\n')
    if not items:
        out.append('  {"", 0, 0, 0, 0, 0, 0, nullptr},\n')
    out.append(f"}};\nextern const size_t kThaiRunCount = {len(items)};\n")
    OUT_RUNS.write_text("".join(out))
    return items, total


def preview(items, sizes, path):
    by = {(it[0], it[1]): it for it in items}

    def blit(img, x, base, it):
        bm = Image.new("1", (it[2], it[3]))
        bpr = (it[2] + 7) // 8
        for y in range(it[3]):
            for xx in range(it[2]):
                if it[7][y * bpr + xx // 8] & (0x80 >> (xx % 8)):
                    bm.putpixel((xx, y), 1)
        img.paste(0, (x + it[4], base + it[5]), bm)
        return x + it[6]

    def compose(img, x, base, fid, text):
        weight = IDS[fid][1]
        font = load(weight, sizes[fid], False)
        parts, cur = [], ""
        for c in text:
            if is_thai(c) or (cur and c in "./"):
                cur += c
            else:
                if cur:
                    parts.append(cur)
                    cur = ""
                parts.append(c)
        if cur:
            parts.append(cur)
        for p in parts:
            if is_thai(p[0]):
                x = blit(img, x, base, by[(p, fid)])
            else:
                bm, left, top = render(font, p)
                if bm is not None:
                    img.paste(0, (x + left, base + top), bm)
                x += round(font.getlength(p))
        return x

    samples = ["26 พฤศจิกายน 2569", "ความชื้น 61%", "ลม ตะวันออกเฉียงเหนือ 2 กม./ชม.", "ไม่มี WiFi"]
    rows = []
    for fid in (1, 6):
        for s in samples:
            rows.append((fid, s))
        for r in sorted({k[0] for k in by}):
            if (r, fid) in by:
                rows.append((fid, r))
    heights = [sizes[f] * 2 + 12 for f, _ in rows]
    img = Image.new("1", (900, sum(heights) + 10), 1)
    y = 5
    for (fid, s), h in zip(rows, heights):
        compose(img, 10, y + int(sizes[fid] * 1.4), fid, s)
        y += h
    path.parent.mkdir(parents=True, exist_ok=True)
    img.convert("L").save(path)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--preview", type=Path)
    args = ap.parse_args()
    OUT_FONTS.mkdir(parents=True, exist_ok=True)

    sizes, flash_fonts = [], 0
    print("Id       Prompt                 English H  px")
    for fid, (idname, weight, eng) in enumerate(IDS):
        target = english_h_height(eng)
        px = pick_px(weight, target)
        sizes.append(px)
        name, n = gen_ascii(weight, px)
        flash_fonts += n
        print(f"{idname:8} {name:22} {eng:20} H={target:2} px={px}")

    runs = scan_runs()
    items, total = gen_runs(runs, sizes)
    print(f"{len(runs)} unique runs, {len(items)} bitmaps, {total} bitmap bytes, ASCII font bytes {flash_fonts}")
    if args.preview:
        preview(items, sizes, args.preview)


if __name__ == "__main__":
    main()
